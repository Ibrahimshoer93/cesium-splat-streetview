// Per-dataset configuration for the native 3D Tiles + KHR_gaussian_splatting
// pipeline. A new dataset is added by exporting a `DatasetConfig` from
// `src/datasets/<id>.ts` and registering it in `src/datasets/index.ts`.

export interface DatasetSplatTileset {
    kind: "tileset";
    /** URL of the 3D Tiles `tileset.json` produced by
     *  `3dgs-ply-3dtiles-converter`. Can be a single string OR an array of
     *  strings when the source PLY has been split into multiple chunks.
     *  Each URL loads as its own Cesium3DTileset primitive; they share the
     *  same geographic anchor and Cesium frustum-culls them together.
     *  Use this for self-hosted tilesets in `public/data/`. Mutually
     *  exclusive with `ionAssetIds`. */
    tilesetUrl?: string | string[];
    /** Array of Cesium Ion asset IDs. Each ID loads via
     *  `Cesium3DTileset.fromIonAssetId` and uses the Ion default access
     *  token (set from `VITE_CESIUM_ION_TOKEN`). Same orientation/altitude
     *  fixes apply across all of them. Mutually exclusive with
     *  `tilesetUrl`. */
    ionAssetIds?: number[];
    /** Maximum screen-space-error in pixels. Lower = more refinement (more
     *  detail, more memory); higher = coarser. Cesium default is 16. */
    maximumScreenSpaceError?: number;
    /** Per-axis rotation applied to `root.transform` after load (degrees).
     *  Compensates for input-convention mismatch when the converter assumed
     *  a different intrinsic frame than the PLY actually uses.
     *  - Lublin PLY is UTM-ENU (Y=north, Z=up). Converter used graphdeco
     *    (Y=down, Z=forward). +90° around X puts Z back to up. */
    orientationFixDeg?: { x?: number; y?: number; z?: number };
    /** Shift the tileset along the local ENU up vector by this many meters.
     *  Useful when the converter's `--coordinate height` was off — bakes the
     *  correction in without re-running the (hours-long) conversion. Iterate
     *  live with `window.__nudgeHeight(deltaM)` in devtools. */
    additionalHeightM?: number;
}

export type DatasetSplat = DatasetSplatTileset;

/** Street-view "walk mode" configuration. When present, the dataset is treated
 *  as a ground capture: the camera is constrained to within `radiusM` of the
 *  nearest captured waypoint, the standard flyover controls are replaced with
 *  WASD-style walking, and the demo flow lands at eye height instead of
 *  flyover altitude. */
export interface WalkMode {
    /** Public-relative URL of the waypoints JSON file. Schema:
     *  `{ version, anchor_wgs84:[lat,lon,h], waypoints: [{lat,lon,height_m,heading_deg,pitch_deg,ts}] }`.
     *  Generated by `tools/kinaliada_poses/generate_waypoints.py`. */
    waypointsUrl: string;
    /** Maximum allowed distance (meters, horizontal) between the camera and
     *  the nearest waypoint. Beyond this, the camera is snapped back toward
     *  the nearest waypoint along the breach vector. */
    radiusM: number;
    /** Eye height above the underlying waypoint height (meters). Walking moves
     *  the camera in the horizontal plane at `waypoint.height + eyeHeightM`. */
    eyeHeightM?: number;
}

export interface DatasetConfig {
    id: string;
    displayName: string;
    description?: string;

    splat: DatasetSplat;

    /** Camera fly-to on the "→ Fly to ..." button click. */
    initialFlyTo?: {
        lon: number;
        lat: number;
        height: number;
        heading?: number;
        pitch?: number;
        durationSec?: number;
    };

    /** Demo flow "hero" point. After the establish + fly-in, the demo flies
     *  here at flyover altitude and glides. Falls back to initialFlyTo. */
    heroLocation?: { lon: number; lat: number };
    heroGlideHeadingDeg?: number;
    heroGlideDistanceM?: number;

    /** When set, switches the dataset into street-view walk-mode (see WalkMode
     *  above). When omitted, the dataset uses the default aerial flyover
     *  controls (Lublin-style). Mutually exclusive UX-wise — main.ts picks
     *  one controller based on whether this field is present. */
    walkMode?: WalkMode;

    /** Verbatim attribution string required by the dataset's license. */
    attribution?: string;
    /** Notes about restricted uses (license terms). */
    prohibitedUses?: string[];
}
